impl Clip {
    pub fn frames(&self) -> usize {
        self.raw.len()
    }

    /// Frame `i` (wrapping): (raw, clean).
    pub fn at(&self, i: usize) -> (f32, f32) {
        let i = i % self.raw.len();
        (self.raw[i], self.clean[i])
    }
}
